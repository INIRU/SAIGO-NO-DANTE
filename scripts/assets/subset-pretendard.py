#!/usr/bin/env python3
"""
Splits public/fonts/PretendardVariable.woff2 (2 MB, preloaded on every page) into unicode-range subsets.

- core: Latin, punctuation, symbols, compatibility jamo and the 2,350 KS X 1001 syllables (preloaded; covers the UI
  text and almost all game text).
- ext: every other glyph of the font (the remaining 8,822 syllables, kana, Cyrillic, ...); the browser downloads it
  only when a page shows one of its characters.
- latin: the non-Hangul part of core, for the en/ja bold headings.

ext and latin list exactly the code points they have, so a character missing from them never triggers their download.
core is preloaded anyway, so its range covers the whole syllable block: a rare syllable falls through to ext. Writes the
woff2 files to public/fonts/pretendard/ and the next/font declarations to app/pretendard.ts.

  pip install fonttools brotli
  python3 scripts/assets/subset-pretendard.py
"""
import os
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, 'public/fonts/PretendardVariable.woff2')
OUT_DIR = os.path.join(ROOT, 'public/fonts/pretendard')
MODULE = os.path.join(ROOT, 'app/pretendard.ts')

# Non-Hangul blocks kept in core: Latin to Latin Extended-B, spacing modifiers, punctuation through misc symbols and
# arrows, CJK punctuation, compatibility jamo, enclosed CJK and CJK compatibility (units), full-width forms.
HANGUL_SYLLABLES = set(range(0xAC00, 0xD7A4))
CORE_BLOCKS = [(0x0000, 0x024F), (0x02B0, 0x02FF), (0x2000, 0x2BFF), (0x3000, 0x303F), (0x3131, 0x318F),
               (0x3200, 0x33FF), (0xFF00, 0xFFEF)]


def ks_x_1001_syllables():
    syllables = set()
    for high in range(0xB0, 0xC9):
        for low in range(0xA1, 0xFF):
            try:
                char = bytes([high, low]).decode('euc_kr')
            except UnicodeDecodeError:
                continue
            if 0xAC00 <= ord(char) <= 0xD7A3:
                syllables.add(ord(char))
    return syllables


def unicode_range(codes):
    ranges = []
    for code in sorted(codes):
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    return ','.join(f'U+{a:X}' if a == b else f'U+{a:X}-{b:X}' for a, b in ranges)


def write_subset(codes, name):
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.name_IDs = ['*']
    options.notdef_outline = True
    font = TTFont(SOURCE)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codes)
    subsetter.subset(font)
    font.flavor = 'woff2'
    path = os.path.join(OUT_DIR, name)
    font.save(path)
    kept = set(TTFont(path).getBestCmap())
    print(f'{name}: {len(kept)} code points, {os.path.getsize(path) // 1024} KB')
    return kept


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    cmap = set(TTFont(SOURCE).getBestCmap())
    latin = {code for code in cmap if any(a <= code <= b for a, b in CORE_BLOCKS) and not 0xAC00 <= code <= 0xD7A3}
    core = latin | (ks_x_1001_syllables() & cmap)
    ext = cmap - core
    core_kept = write_subset(core, 'PretendardVariable-core.woff2')
    ext_kept = write_subset(ext, 'PretendardVariable-ext.woff2')
    latin_kept = write_subset(latin, 'PretendardVariable-latin.woff2')
    assert not core_kept & ext_kept, 'core and ext must not overlap'
    with open(MODULE, 'w', encoding='utf8') as out:
        out.write(f'''// Generated by scripts/assets/subset-pretendard.py; do not edit by hand.
// next/font needs literal options, so the unicode ranges are written out here.
import localFont from 'next/font/local'

/** Pretendard for Latin, symbols and the 2,350 common syllables: preloaded on every page. */
export const pretendardCore = localFont({{
  src: '../public/fonts/pretendard/PretendardVariable-core.woff2',
  weight: '45 920',
  style: 'normal',
  variable: '--font-pretendard-core',
  display: 'swap',
  preload: true,
  fallback: ['Apple SD Gothic Neo', 'Malgun Gothic', 'sans-serif'],
  declarations: [{{ prop: 'unicode-range', value: '{unicode_range(core_kept - HANGUL_SYLLABLES)},U+AC00-D7A3' }}],
}})

/** The rest of Pretendard (rare syllables, kana, Cyrillic, ...): downloaded only when a page shows one of them. */
export const pretendardExt = localFont({{
  src: '../public/fonts/pretendard/PretendardVariable-ext.woff2',
  weight: '45 920',
  style: 'normal',
  variable: '--font-pretendard-ext',
  display: 'swap',
  preload: false,
  adjustFontFallback: false,
  declarations: [{{ prop: 'unicode-range', value: '{unicode_range(ext_kept)}' }}],
}})

/** en/ja headings are always bold, like KOTRA Bold on Korean pages; other characters fall through to --font-pretendard. */
export const pretendardHeadingLatin = localFont({{
  src: '../public/fonts/pretendard/PretendardVariable-latin.woff2',
  weight: '700',
  variable: '--font-heading-latin',
  display: 'swap',
  preload: false,
  fallback: ['Segoe UI', 'sans-serif'],
  declarations: [{{ prop: 'unicode-range', value: '{unicode_range(latin_kept)}' }}],
}})
''')
    print(f'wrote {os.path.relpath(MODULE, ROOT)}')


if __name__ == '__main__':
    main()
