import { test, expect } from '@playwright/test'
test.use({ channel: 'chrome' })
for (const width of [1440, 390]) test(`compact constraints and vertical plan at ${width}px`, async ({ page, request }) => {
  test.setTimeout(120000)
  await page.setViewportSize({ width, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/ko/planner?tab=floor', {waitUntil: 'domcontentloaded'})
  await page.getByRole('button', { name: /11층/ }).first().click()
  const section = page.locator('[data-floor-constraints="11"]').filter({ visible: true })
  const cards = section.getByRole('button')
  await expect(cards).toHaveCount(6)
  const card = cards.first()
  const rem = await page.evaluate(() => parseFloat(getComputedStyle(document.documentElement).fontSize))
  expect((await card.boundingBox())!.width).toBeLessThanOrEqual(12.5 * rem + 1)
  expect((await card.boundingBox())!.width).toBeGreaterThan(10 * rem)
  await card.focus()
  await page.keyboard.press('Space')
  await expect(card).toHaveAttribute('aria-pressed', 'true')
  await page.keyboard.press('Space')
  await expect(card).toHaveAttribute('aria-pressed', 'false')
  for (const img of await section.locator('img').all()) {
    await img.scrollIntoViewIfNeeded()
    await img.evaluate((node: HTMLImageElement) => { node.loading = 'eager'; return Promise.race([node.decode(), new Promise((_, reject) => setTimeout(() => reject(Error('Image decode timed out: ' + node.src)), 10000))]) })
  }
  await expect(section.locator('img[alt="거던 패스"]').first()).toHaveAttribute('src', /md-pass/)
  expect(await section.evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
  await section.screenshot({ path: `/tmp/limbus-constraints-${width}.png` })
  const response = await request.get('/api/discovery?kind=planner&days=0')
  expect(response.ok()).toBe(true)
  const data = await response.json()
  const plan = data.recent.find((row: { floor_plan?: {gift_ids: string[]}[] }) => row.floor_plan?.some(floor => floor.gift_ids.length > 5)) ?? data.recent[0]
  expect(plan).toBeTruthy()
  await page.goto(`/ko/planner/community/${plan.id}`, {waitUntil: 'domcontentloaded'})
  const rows = page.locator('.floor-preview-row')
  await expect(rows.first()).toBeVisible()
  const box = await rows.first().boundingBox()
  if (await rows.count() > 1) expect((await rows.nth(1).boundingBox())!.y).toBeGreaterThan(box!.y + box!.height)
  await expect(page.getByText('테마팩 보스', { exact: true })).toHaveCount(0)
  await expect(page.getByText('테마팩 전용 · 떠나기 전에 획득을 확인하세요.', { exact: true })).toHaveCount(0)
  const warning = page.locator('[data-gift-warning]').first()
  await expect(warning).toBeVisible()
  expect((await warning.boundingBox())!.width).toBeLessThanOrEqual(rem)
  await warning.locator('..').hover()
  await expect(warning).toBeVisible()
  await warning.locator('..').focus()
  await expect(warning.locator('..')).toBeFocused()
  const expectedFrontline = plan.deck.filter((slot: {slot_order: number}) => slot.slot_order >= 0 && slot.slot_order < 6).length
  const expectedBackup = plan.deck.filter((slot: {slot_order: number}) => slot.slot_order >= 6 && slot.slot_order < 99).length
  await expect(page.locator('[data-formation="selected"]')).toHaveCount(expectedFrontline)
  await expect(page.locator('[data-formation="backup"]')).toHaveCount(expectedBackup)
  await rows.nth(9).scrollIntoViewIfNeeded()
  await page.screenshot({path: `/tmp/limbus-guidance-${width}.png`})
  await rows.first().scrollIntoViewIfNeeded()
  for (const img of await rows.first().locator('img').all()) await img.evaluate((node: HTMLImageElement) => { node.loading = 'eager'; return Promise.race([node.decode(), new Promise((_, reject) => setTimeout(() => reject(Error('Image decode timed out: ' + node.src)), 10000))]) })
  await page.screenshot({ path: `/tmp/limbus-plan-${width}.png` })
  expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
})
