import {test,expect} from '@playwright/test'
test.use({channel:'chrome'})
for(const width of [1440,390])test(`floor original layers, Korean document, discovery ${width}`,async({page},info)=>{
 test.setTimeout(90000)
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text().slice(0,180))})
 await page.setViewportSize({width,height:1000})
 await page.goto('/ko/planner')
 await page.getByRole('button',{name:'층별 계획',exact:true}).click()
 const floor=page.getByRole('button',{name:/11층/}).first()
 await floor.click()
 const cards=page.locator('[data-floor-constraints="11"]')
 await expect(cards).toBeVisible()
 await expect(cards.getByRole('button',{pressed:false})).toHaveCount(6)
 await cards.getByRole('button',{name:/자아 간섭/}).click()
 await expect(cards.getByRole('button',{name:/자아 간섭/})).toHaveAttribute('aria-pressed','true')
 for(const img of await cards.locator('img').all())await img.evaluate((i:HTMLImageElement)=>i.decode())
 await cards.screenshot({path:info.outputPath(`constraints-${width}.png`)})
 await page.getByRole('button',{name:'미리보기',exact:true}).click()
 const editor=page.getByRole('textbox',{name:'상세 메모'})
 await editor.fill('갂 뷁 힣 한글 메모가 유지됩니다')
 await expect(editor).toHaveText('갂 뷁 힣 한글 메모가 유지됩니다')
 await page.getByRole('button',{name:/^양식 넣기/}).click()
 await page.getByRole('menuitem',{name:'기본 양식'}).click()
 await expect(editor).toContainText('운용 순서')
 await expect(editor).toContainText('갂 뷁 힣')
 await page.getByRole('button',{name:'임시 저장',exact:true}).click()
 await page.getByRole('menuitem',{name:'저장',exact:true}).first().click()
 await page.reload()
 await page.getByRole('button',{name:'임시 저장',exact:true}).click()
 await page.getByRole('menuitem',{name:'불러오기',exact:true}).first().click()
 await page.getByRole('button',{name:'미리보기',exact:true}).click()
 await expect(editor).toContainText('갂 뷁 힣')
 await expect(page.locator('[data-floor-constraints="11"]').filter({visible:true})).toBeVisible()
 await editor.screenshot({path:info.outputPath(`notes-${width}.png`)})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
 await page.goto('/ko/decks')
 await expect(page.locator('[data-discovery-shelf]').filter({visible:true})).toBeVisible()
 await expect(page.locator('[data-discovery-empty]').filter({visible:true})).toBeVisible()
 await expect(page.getByText('아직 집계할 게시물이 없습니다.',{exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'전체보기 · 필터',exact:true}).click()
 await expect(page.locator('[data-discovery-shelf]').filter({visible:true})).toHaveCount(0)
 const back = page.locator('[data-board-back]').filter({visible:true})
 await expect(back).toBeVisible()
 await back.focus()
 await page.keyboard.press('Enter')
 await expect(page.locator('[data-discovery-shelf]').filter({visible:true})).toBeVisible()
 await expect(page.getByText('기록 지우기',{exact:true})).toHaveCount(0)
 await expect(page.getByText('기록·집계 끄기',{exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'전체보기 · 필터',exact:true}).click()
 await page.goBack()
 await expect(page.locator('[data-discovery-shelf]').filter({visible:true})).toBeVisible()
 await page.goto('/ko/planner/community')
 await expect(page.locator('[data-discovery-shelf]').filter({visible:true})).toBeVisible()
 await page.goto('/ko/planner/community?browse=all')
 await expect(page.locator('[data-board-back]').filter({visible:true})).toBeVisible()
 await page.locator('[data-board-back]').filter({visible:true}).click()
 await expect(page.locator('[data-discovery-shelf]').filter({visible:true})).toBeVisible()
 await page.goto('/ko/developers')
 await expect(page.getByRole('heading',{name:/개발자/})).toBeVisible()
 await expect(page.getByText('Application error',{exact:false})).toHaveCount(0)
 expect(errors).toEqual([])
})
