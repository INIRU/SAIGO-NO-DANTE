import { test, expect } from '@playwright/test'
test.use({ channel: 'chrome' })
test('keyword categories filter the restored catalog after reload', async ({page}) => {
  test.setTimeout(90000)
  await page.goto('/ko/keywords')
  const status = page.getByRole('button', {name:/^상태이상\s*\d+$/})
  await expect(status).toBeVisible({timeout:60000})
  await expect(status).not.toHaveText(/상태이상\s*0$/)
  for (const label of ['버프','디버프','고유']) await expect(page.getByRole('button',{name:new RegExp(`^${label}\\s*\\d+$`)})).not.toHaveText(new RegExp(`${label}\\s*0$`))
  await status.click()
  await expect(status).toHaveAttribute('aria-pressed','true')
  await expect(page.getByText('화상',{exact:true})).toBeVisible()
  await expect(page.getByText('피해량 증가',{exact:true})).toHaveCount(0)
  await page.reload()
  await expect(status).toHaveAttribute('aria-pressed','true')
  await page.screenshot({path:'/tmp/limbus-keywords-fixed.png',fullPage:true})
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth)).toBeLessThanOrEqual(1)
})
