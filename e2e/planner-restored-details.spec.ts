import { test, expect } from '@playwright/test'
test.use({ channel: 'chrome' })
test('restored planner IDs expose skills, passives and supplied formation banners after reload', async ({ page }) => {
  await page.goto('/ko/planner/community/4c84e6ec-b046-40fc-b5a6-261dc03b3866')
  await expect(page.getByRole('region', { name: '나를 위한 AI 요약' })).toHaveCount(0)
  const selected = page.locator('img[src*="selected-"]').first()
  const backup = page.locator('img[src*="backup-"]').first()
  await expect(selected).toBeVisible(); await expect(backup).toBeVisible()
  await selected.evaluate((image: HTMLImageElement) => image.decode())
  await backup.evaluate((image: HTMLImageElement) => image.decode())
  await expect(page.getByRole('button', { name: /^배틀 \([1-9]/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /^서포트 \([1-9]/ })).toBeVisible()
  const identity = page.getByRole('button', { name: /마침표 사무소 대표/ }).first()
  await identity.click()
  const modal = page.getByRole('dialog')
  await expect(modal).toBeVisible()
  await expect(modal.getByText('스킬 정보 없음', { exact: true })).toHaveCount(0)
  await expect(modal.getByRole('button', { name: /패시브\s*[1-9]/ })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.reload()
  await expect(backup).toBeVisible()
  expect((await page.request.post('/api/ai/summary', { data: {} })).status()).toBe(404)
})
